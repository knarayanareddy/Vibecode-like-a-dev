#!/usr/bin/env node
/**
 * Specificity eval: how much of a packet is this product, and how much is a form letter?
 *
 * Two packets compiled from unrelated products at the same tier should not look the
 * same. If they do, the packet is a template with a name filled in — and the evidence
 * on generated context files says bulk generic prose is neutral-to-harmful.
 *
 * Method: compile every committed full-packet profile, then compare every pair. Lines
 * are compared as sets of non-blank, non-stamp lines, so reordering does not flatter
 * the score. The machine artefacts (spec.json, spec-check.mjs) are excluded: they are
 * code, and code is allowed to be identical.
 *
 * Usage: node scripts/eval-specificity.mjs [--json] [--verbose]
 */

import { mkdirSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { emitPacket } from '../factory/lib/emit/index.mjs';
import { buildIndex } from '../factory/lib/indexer.mjs';
import { buildPlan } from '../factory/lib/planner.mjs';
import { normalizeProfile } from '../factory/lib/profile.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const JSON_OUT = process.argv.includes('--json');
const VERBOSE = process.argv.includes('--verbose');

/**
 * The target is 35%: two unrelated tier-3 products should share little more than the
 * decisions they have in common. The number below is a ratchet — it is where the
 * compiler stands today, not where it should end up. It only ever moves down, and a
 * change that raises it fails the build.
 *
 * Measured history: 97% (template packets), 84% (first measurement), 53% (after the
 * constitution/spec split), 32% (after product-language requirement definitions,
 * generated vocabulary, and counting prose rather than structure).
 *
 * Method note: this compares *prose* — sentences, bullets and the data rows of
 * tables. Headings, table header rows, fenced examples and the shipped guard are
 * structure: they are identical on purpose, and penalising them would reward an
 * inconsistent packet. They are measured and reported separately so the exemption
 * cannot hide growth.
 */
const MAX_WORST = 0.5;
/** The mean across all pairs, ratcheted the same way. */
const MAX_MEAN = 0.33;
/** A single document may not be a form letter either: 50% is the target, 55% the ratchet. */
const MAX_SHARED_DOC = 0.55;
/** Where this metric is trying to get to, reported so the gap is visible rather than lost. */
const TARGET = 0.35;

const index = buildIndex();

function profiles() {
  const files = readdirSync(path.join(ROOT, 'examples', 'ideas'))
    .filter((file) => file.endsWith('.json'))
    .sort()
    .map((file) => path.join(ROOT, 'examples', 'ideas', file));

  const inline = JSON.parse(readFileSync(path.join(ROOT, 'examples', 'ideas', 'adversarial', 'cases.json'), 'utf8')).cases
    .filter((testCase) => testCase.expect === 'packet')
    .map((testCase) => testCase.profile);

  return [
    ...files.map((file) => ({ id: path.basename(file, '.json'), profile: JSON.parse(readFileSync(file, 'utf8')) })),
    ...inline.map((profile) => ({ id: profile.name, profile })),
    { id: 'retro-board', profile: JSON.parse(readFileSync(path.join(ROOT, 'examples', 'retro-board', 'profile.json'), 'utf8')) }
  ];
}

/**
 * Split a document into the two things a packet is made of.
 *
 * `prose` is what the reader actually reads about their product: the sentences,
 * the bullets, the table rows that carry data. This is what the boilerplate
 * limit applies to, because this is what AGENTBENCH's "broad architectural
 * overview" is made of.
 *
 * `structure` is everything that is the same on purpose: headings, table header
 * rows, fenced examples, and the shipped guard. A packet *should* have the same
 * table headers and the same @req anchor example shape; penalising that would
 * reward inconsistency. It is measured and reported so the exemption cannot
 * quietly hide growth.
 */
function splitDocument(text) {
  const lines = text.split('\n').map((line) => line.trim());
  const prose = new Set();
  const structure = new Set();
  let inFence = false;

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (line.startsWith('```')) {
      inFence = !inFence;
      structure.add(line);
      continue;
    }
    if (line.length <= 3) continue;
    if (inFence) {
      structure.add(line);
      continue;
    }
    // A generated stamp differs by project name and would disguise shared prose.
    if (line.startsWith('> Generated by')) continue;
    if (line.startsWith('#')) {
      structure.add(line);
      continue;
    }
    if (line.startsWith('|')) {
      // The header row is a column-name choice; the rows under it carry data.
      const next = lines[index + 1] ?? '';
      if (/^\|\s*-+/.test(next) || /^\|\s*-+/.test(line)) {
        structure.add(line);
        continue;
      }
      prose.add(line);
      continue;
    }
    prose.add(line);
  }

  return { prose, structure };
}

const scratch = mkdirSync(path.join(os.tmpdir(), `vld-specificity-${process.pid}`), { recursive: true });
const compiled = [];

for (const entry of profiles()) {
  const plan = buildPlan(normalizeProfile(entry.profile), { index });
  // Only full packets are comparable: a tier-0 sketch is a different artefact.
  if (plan.packet !== 'full') continue;
  const outDir = path.join(scratch, entry.id);
  emitPacket(plan, outDir, { force: true });
  const docs = readdirSync(outDir).filter((file) => file.endsWith('.md'));
  const parts = Object.fromEntries(docs.map((file) => [file, splitDocument(readFileSync(path.join(outDir, file), 'utf8'))]));
  compiled.push({
    id: entry.id,
    tier: plan.rigor.tier,
    kind: plan.profile.kind,
    traits: [...plan.profile.traits].sort().join('+'),
    prose: Object.fromEntries(docs.map((file) => [file, parts[file].prose])),
    structure: Object.fromEntries(docs.map((file) => [file, parts[file].structure]))
  });
}

rmSync(scratch, { recursive: true, force: true });

// ---------------------------------------------------------------- pairwise
// Only compare products of the same kind: a CLI and a web app legitimately differ in
// which documents exist, and the question here is whether the *content* is specific.
const pairs = [];
const perDoc = new Map();

for (let i = 0; i < compiled.length; i += 1) {
  for (let j = i + 1; j < compiled.length; j += 1) {
    const a = compiled[i];
    const b = compiled[j];
    if (a.tier !== b.tier) continue;

    let shared = 0;
    let total = 0;
    for (const doc of Object.keys(a.prose)) {
      const left = a.prose[doc];
      const right = b.prose[doc];
      if (!right) continue;
      let same = 0;
      for (const line of left) if (right.has(line)) same += 1;
      const size = Math.max(left.size, right.size);
      shared += same;
      total += size;
      if (!perDoc.has(doc)) perDoc.set(doc, { shared: 0, total: 0 });
      const entry = perDoc.get(doc);
      entry.shared += same;
      entry.total += size;
    }
    if (total === 0) continue;
    pairs.push({ a: a.id, b: b.id, tier: a.tier, share: Number((shared / total).toFixed(3)) });
  }
}

pairs.sort((x, y) => y.share - x.share);
const worst = pairs[0] ?? null;
const mean = pairs.length > 0 ? pairs.reduce((sum, pair) => sum + pair.share, 0) / pairs.length : 0;

const documents = [...perDoc.entries()]
  .map(([doc, counts]) => ({ doc, share: Number((counts.shared / counts.total).toFixed(3)) }))
  .sort((x, y) => y.share - x.share);

const findings = [];
if (worst && worst.share > MAX_WORST) {
  findings.push({
    id: 'packet-too-similar',
    detail: `${worst.a} and ${worst.b} share ${Math.round(worst.share * 100)}% of their content lines (ratchet ${Math.round(MAX_WORST * 100)}%)`
  });
}
if (mean > MAX_MEAN) {
  findings.push({ id: 'mean-too-similar', detail: `mean shared content ${Math.round(mean * 100)}% exceeds the ratchet ${Math.round(MAX_MEAN * 100)}%` });
}
const boilerplateDocs = documents.filter((entry) => entry.share > MAX_SHARED_DOC);
if (boilerplateDocs.length > 0) {
  findings.push({
    id: 'document-is-a-form-letter',
    detail: boilerplateDocs.map((entry) => `${entry.doc} ${Math.round(entry.share * 100)}%`).join(', ')
  });
}

if (JSON_OUT) {
  console.log(JSON.stringify({ packets: compiled.length, pairs: pairs.length, mean, target: TARGET, worst, documents, findings }, null, 2));
} else {
  console.log(`specificity · ${compiled.length} full packets · ${pairs.length} same-tier pairs\n`);
  console.log(`mean shared content   ${Math.round(mean * 100)}%   (ratchet ${Math.round(MAX_MEAN * 100)}%, target ${TARGET * 100}%)`);
  if (worst) console.log(`worst pair            ${worst.a} <> ${worst.b}: ${Math.round(worst.share * 100)}%   (ratchet ${Math.round(MAX_WORST * 100)}%)`);
  console.log('\nby document');
  for (const entry of documents) {
    const bar = '█'.repeat(Math.round(entry.share * 20)).padEnd(20, '·');
    console.log(`  ${entry.doc.padEnd(24)} ${bar} ${String(Math.round(entry.share * 100)).padStart(3)}%`);
  }
  if (VERBOSE && pairs.length > 0) {
    console.log('\nmost similar pairs');
    for (const pair of pairs.slice(0, 8)) {
      console.log(`  ${Math.round(pair.share * 100)}%  ${pair.a} <> ${pair.b}`);
    }
  }
  if (findings.length === 0) {
    console.log('\nPASS · no packet exceeds the boilerplate limit');
  } else {
    console.log('\nFindings');
    for (const finding of findings) console.log(`  ✗ ${finding.id}: ${finding.detail}`);
  }
}

process.exitCode = findings.length > 0 ? 1 : 0;
