/**
 * Bounded, one-way interoperability exports.
 *
 * These files help an agent already using Spec Kit or Kiro start from a VLD
 * packet. They are generated views, not inputs: profile, overlays, packet and
 * change manifests remain the only requirement/compiler authorities.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { digest, extensionError, stableJson } from './extension-utils.mjs';
import { verifyPacket } from './verify.mjs';

const FORMATS = new Set(['spec-kit', 'kiro']);
const MAX_SOURCE_DOCUMENT_CHARACTERS = 60_000;
const MANIFEST = 'vld-export.json';

function requireFormat(format) {
  if (!FORMATS.has(format)) throw extensionError(`unknown export format "${format}"; expected spec-kit or kiro`, 'INVALID_EXPORT_FORMAT');
  return format;
}

function readPacket(packetDir) {
  const packet = path.resolve(packetDir ?? '');
  if (!existsSync(packet) || !statSync(packet).isDirectory()) throw extensionError(`packet directory does not exist: ${packet}`, 'EXPORT_PACKET_NOT_FOUND');
  const verification = verifyPacket(packet);
  if (!verification.ok) {
    throw extensionError(`refusing to export an invalid VLD packet:\n${verification.errors.map((error) => `- ${error}`).join('\n')}`, 'INVALID_EXPORT_PACKET');
  }
  const specFile = path.join(packet, 'spec.json');
  let spec;
  try { spec = JSON.parse(readFileSync(specFile, 'utf8')); } catch (error) { throw extensionError(`could not read ${specFile}: ${error.message}`, 'INVALID_EXPORT_PACKET'); }
  if (!Array.isArray(spec.requirements) || !spec.project?.name || !spec.project?.title) {
    throw extensionError('packet spec.json is missing project or requirements data required for export', 'INVALID_EXPORT_PACKET');
  }
  return { packet, spec, specDigest: digest(readFileSync(specFile, 'utf8')) };
}

function markdownEscape(value) {
  return String(value ?? '').replace(/\r?\n+/g, ' ').trim();
}

function requirementMarkdown(requirements) {
  return requirements.map((requirement) => {
    const criteria = (requirement.acceptance ?? []).map((criterion) => `  - **${criterion.id}:** ${markdownEscape(criterion.text)}`).join('\n') || '  - No acceptance criterion was emitted.';
    return `### ${requirement.id} — ${markdownEscape(requirement.title)}\n\n${markdownEscape(requirement.statement)}\n\n**Failure path:** ${markdownEscape(requirement.failurePath)}\n\n**Verification:** ${markdownEscape(requirement.verify)}${requirement.anchor ? ` · \`${markdownEscape(requirement.anchor)}\`` : ''}\n\n**Acceptance criteria**\n${criteria}`;
  }).join('\n\n');
}

function taskMarkdown(requirements) {
  return requirements.map((requirement) => {
    const criteria = (requirement.acceptance ?? []).map((criterion) => `  - [ ] ${criterion.id}: ${markdownEscape(criterion.text)}`).join('\n') || '  - [ ] Add an observable acceptance criterion before implementation.';
    return `- [ ] **${requirement.id} — ${markdownEscape(requirement.title)}** (${markdownEscape(requirement.verify)})\n${criteria}`;
  }).join('\n');
}

function sourceDocument(packet, candidates, label) {
  for (const name of candidates) {
    const file = path.join(packet, name);
    if (!existsSync(file)) continue;
    const source = readFileSync(file, 'utf8');
    if (source.length > MAX_SOURCE_DOCUMENT_CHARACTERS) {
      throw extensionError(`${name} exceeds the ${MAX_SOURCE_DOCUMENT_CHARACTERS}-character export bound`, 'EXPORT_SOURCE_TOO_LARGE');
    }
    return `## Derived ${label}\n\n_Source: VLD packet \`${name}\`. This copy is a navigation aid; the packet remains authoritative._\n\n${source.trim()}\n`;
  }
  return `## Derived ${label}\n\nNo ${label.toLowerCase()} document is present in this packet. Consult the VLD packet directly.\n`;
}

function header({ title, source, format }) {
  return `<!-- Generated by vibecode-like-a-dev. Do not edit: regenerate from the compiled VLD packet. -->\n# ${markdownEscape(title)}\n\n> **Derived view only.** This ${format} layout is generated from a compiled VLD packet. It cannot change VLD requirements, policy, profile, overlays, \`spec.json\`, \`delta.json\`, or \`spec.after.json\`. Review and edit those authorities, then export again.\n\n**Source:** \`spec.json\` SHA-256 \`${source.specDigest}\` · VLD ${source.generatedWith.tool ?? 'packet'} ${source.generatedWith.version ?? 'unknown'}\n\n`;
}

function commonFiles(source, format) {
  const { packet, spec, specDigest } = source;
  const project = spec.project;
  const sourceMeta = { specDigest, generatedWith: spec.generatedWith ?? {} };
  const constitution = `${header({ title: `${project.title} — VLD authority boundary`, source: sourceMeta, format })}` +
    `## Intent\n\n${markdownEscape(project.idea)}\n\n` +
    `## Operating rule\n\nTreat the VLD packet as the source of truth. This export is deliberately one-way: agent work and human review may propose changes, but changes become authoritative only through VLD's profile/overlay/change lifecycle.\n\n` +
    `## Rigor\n\nTier ${spec.rigor?.tier ?? 'unknown'} (${markdownEscape(spec.rigor?.label)}); ${spec.requirements.length} requirements; ${(spec.gates ?? []).length} gates.\n`;
  const requirements = `${header({ title: `${project.title} — requirements`, source: sourceMeta, format })}` + requirementMarkdown(spec.requirements) + '\n';
  const tasks = `${header({ title: `${project.title} — implementation checklist`, source: sourceMeta, format })}` +
    `These are traceable implementation prompts, not a replacement for VLD's delivery plan or human task breakdown. Marking a box here never changes requirement status in \`spec.json\`.\n\n` + taskMarkdown(spec.requirements) + '\n';
  const design = `${header({ title: `${project.title} — design context`, source: sourceMeta, format })}` +
    sourceDocument(packet, ['03-architecture.md', '02-domain-model.md', 'spec.md'], 'architecture context') +
    sourceDocument(packet, ['06-delivery-plan.md'], 'delivery context');
  return { constitution, requirements, tasks, design };
}

function formatFiles(format, source) {
  const common = commonFiles(source, format === 'spec-kit' ? 'Spec Kit' : 'Kiro');
  if (format === 'spec-kit') {
    return {
      '.specify/memory/constitution.md': common.constitution,
      'specs/vld-packet/spec.md': common.requirements,
      'specs/vld-packet/plan.md': common.design,
      'specs/vld-packet/tasks.md': common.tasks,
      'README.md': `${header({ title: 'VLD → Spec Kit export', source: { specDigest: source.specDigest, generatedWith: source.spec.generatedWith ?? {} }, format: 'Spec Kit' })}Open \`specs/vld-packet/spec.md\`, then \`plan.md\` and \`tasks.md\`. These files are a bounded interoperability view, not a Spec Kit project lifecycle and not VLD compiler input.\n`
    };
  }
  return {
    '.kiro/steering/vld-packet.md': common.constitution,
    '.kiro/specs/vld-packet/requirements.md': common.requirements,
    '.kiro/specs/vld-packet/design.md': common.design,
    '.kiro/specs/vld-packet/tasks.md': common.tasks,
    'README.md': `${header({ title: 'VLD → Kiro export', source: { specDigest: source.specDigest, generatedWith: source.spec.generatedWith ?? {} }, format: 'Kiro' })}Open \`.kiro/specs/vld-packet/requirements.md\`, then \`design.md\` and \`tasks.md\`. Steering and spec files are generated views; VLD's packet and change lifecycle retain authority.\n`
  };
}

function outputIsEmpty(directory) {
  return !existsSync(directory) || readdirSync(directory).length === 0;
}

function canReplacePriorExport(directory, format) {
  const file = path.join(directory, MANIFEST);
  if (!existsSync(file)) return false;
  try {
    const manifest = JSON.parse(readFileSync(file, 'utf8'));
    return manifest?.schemaVersion === 1 && manifest?.generatedBy === 'vibecode-like-a-dev' && manifest?.format === format;
  } catch { return false; }
}

/** Generate a small, deterministic view of a verified packet for one supported ecosystem. */
export function exportPacket({ format, packetDir, outDir, force = false }) {
  requireFormat(format);
  if (!outDir) throw extensionError('export output directory is required', 'EXPORT_OUTPUT_REQUIRED');
  const source = readPacket(packetDir);
  const out = path.resolve(outDir);
  if (out === source.packet || out.startsWith(`${source.packet}${path.sep}`)) {
    throw extensionError('export output must be outside the authoritative packet directory', 'EXPORT_OUTPUT_INSIDE_PACKET');
  }
  if (existsSync(out) && !statSync(out).isDirectory()) throw extensionError(`export output is not a directory: ${out}`, 'EXPORT_OUTPUT_NOT_DIRECTORY');
  if (!outputIsEmpty(out) && !force) throw extensionError(`${out} is not empty; choose an empty directory or pass --force to replace generated files`, 'EXPORT_OUTPUT_NOT_EMPTY');
  if (!outputIsEmpty(out) && force && !canReplacePriorExport(out, format)) {
    throw extensionError(`${out} is not a prior ${format} VLD export; --force only replaces generated export files`, 'EXPORT_OUTPUT_NOT_REPLACEABLE');
  }

  const files = formatFiles(format, source);
  const paths = Object.keys(files).sort();
  const manifest = {
    schemaVersion: 1,
    format,
    generatedBy: 'vibecode-like-a-dev',
    source: {
      authority: 'compiled VLD packet; spec.json, delta.json and spec.after.json remain authoritative',
      project: source.spec.project.name,
      specDigest: source.specDigest,
      generatedWith: source.spec.generatedWith ?? {},
      requirements: source.spec.requirements.length,
      gates: (source.spec.gates ?? []).length
    },
    files: paths.map((file) => ({ file, digest: digest(files[file]) })),
    limits: { maxSourceDocumentCharacters: MAX_SOURCE_DOCUMENT_CHARACTERS, sourceIsReadOnly: true }
  };
  files[MANIFEST] = `${stableJson(manifest)}\n`;

  mkdirSync(out, { recursive: true });
  for (const [relative, content] of Object.entries(files)) {
    const target = path.join(out, relative);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content, 'utf8');
  }
  return { format, packet: source.packet, out, manifest: path.join(out, MANIFEST), files: Object.keys(files).sort(), source: manifest.source };
}
